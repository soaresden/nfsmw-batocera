"""Writes batocera/tools/Identifier NFSMW.sh, the on-console identification script.

    python3 batocera/tools/gen_identifier.py <speedbreaker checkout>

It embeds the SHA-256 of every known default.xex (tools/editions/regional/ediciones.json) and SpeedBreaker's two
file lists (runtime/install/manifest.inc for the USA disc, manifest_pal_es.inc for the PAL Spanish one): names,
sizes and hashes only, no game content.
"""
import json
import os
import re
import sys

RAIZ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SALIDA = os.path.join(RAIZ, 'batocera', 'tools', 'Identifier NFSMW.sh')

SCRIPT = r'''#!/bin/bash
# Identifies a copy of NFS Most Wanted (Xbox 360) on the console, for SpeedBreaker and for this port.
# Generated by batocera/tools/gen_identifier.py: edit that file, not this one.
#
# As a Port: copy it to /userdata/roms/ports/ and launch it, or over SSH:  bash "Identifier NFSMW.sh" [folder]
# It looks in speedbreaker/disc and nfsmw/game_root (or the folder given), hashes the files and writes
# /userdata/roms/ports/nfsmw-identification.txt. Hashing ~7 GB takes a minute or two. Nothing is changed.
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/nfsmw-identification.txt"
DIR="${1:-}"
if [ -z "$DIR" ]; then
  for d in "$HERE/speedbreaker/disc" "$HERE/nfsmw/game_root" "$HERE/disc" "$HERE"; do
    [ -f "$d/default.xex" ] && DIR="$d" && break
  done
fi
exec > "$OUT" 2>&1
echo "== NFSMW identification $(date '+%F %T')"
[ -f "$DIR/default.xex" ] || { echo "default.xex not found (looked in speedbreaker/disc, nfsmw/game_root, disc/)"; exit 1; }
echo "folder: $DIR"

# default.xex of every known edition (tools/editions/regional/ediciones.json)
EDITIONS='@EDITIONS@'
# SpeedBreaker's file lists: SHA-256, size, path.
SB_USA='@USA@'
SB_PAL_ES='@ES@'

xex=$(sha256sum "$DIR/default.xex" | cut -d' ' -f1)
echo "default.xex sha256: $xex  size: $(stat -c %s "$DIR/default.xex")"
ed=$(echo "$EDITIONS" | grep "^$xex " | cut -d' ' -f2-)
echo "edition: ${ed:-UNKNOWN (modified or unlisted executable)}"
echo
echo "== files"
(cd "$DIR" && find . -type f | sed 's|^\./||' | sort | while read -r f; do echo "$(stat -c %s "$f") $f"; done)
echo
for list in USA PAL_ES; do
  if [ $list = USA ]; then data="$SB_USA"; else data="$SB_PAL_ES"; fi
  ok=0; bad=0; missing=0
  echo "== SpeedBreaker $list check"
  while read -r hash size path; do
    [ -n "$path" ] || continue
    if [ ! -f "$DIR/$path" ]; then echo "  MISSING  $path"; missing=$((missing+1)); continue; fi
    if [ "$(stat -c %s "$DIR/$path")" != "$size" ]; then echo "  SIZE     $path"; bad=$((bad+1)); continue; fi
    if [ "$(sha256sum "$DIR/$path" | cut -d' ' -f1)" != "$hash" ]; then echo "  CHANGED  $path"; bad=$((bad+1)); continue; fi
    ok=$((ok+1))
  done <<< "$data"
  echo "  $ok identical, $bad different, $missing missing (of 49)"
done
echo
echo "== done"
'''


def manifest(path):
    texto = open(path, encoding='utf-8').read()
    filas = [f'{h} {size} {name}' for name, size, h in
             re.findall(r'MANIFEST_FILE\("([^"]+)", (\d+)ull, "([0-9a-f]{64})"\)', texto)]
    if len(filas) != 49:
        sys.exit(f'{path}: {len(filas)} files instead of 49')
    return filas


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sb = sys.argv[1]
    ediciones = json.load(open(os.path.join(RAIZ, 'tools', 'editions', 'regional', 'ediciones.json'),
                               encoding='utf-8'))['ediciones']
    filas = [f'{h} {clave} {datos["nombre"]}' for clave, datos in ediciones.items() for h in datos['sha256']]
    usa = manifest(os.path.join(sb, 'runtime', 'install', 'manifest.inc'))
    es = manifest(os.path.join(sb, 'runtime', 'install', 'manifest_pal_es.inc'))
    texto = SCRIPT.replace('@EDITIONS@', '\n'.join(filas)).replace('@USA@', '\n'.join(usa)).replace('@ES@', '\n'.join(es))
    with open(SALIDA, 'w', encoding='utf-8', newline='\n') as f:
        f.write(texto)
    os.chmod(SALIDA, 0o755)
    print(SALIDA)


if __name__ == '__main__':
    main()
